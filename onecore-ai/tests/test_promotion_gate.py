from onecore.data import classify_record_data, validate_manifest
from onecore.evaluate import REQUIRED_METRICS, promotion_gate


def _metrics(data_verified=True, data_kind="synthetic_verified"):
    checkpoint_sha = "a" * 64
    validation_hash = "b" * 64
    test_hash = "c" * 64
    thresholds = {}
    values = {key: 1.0 for key in REQUIRED_METRICS}
    for key in REQUIRED_METRICS:
        thresholds[key] = 2.0
        thresholds[f"test_{key}"] = 2.0
    test_metrics = {
        **values,
        "split": "test",
        "checkpoint_sha256": checkpoint_sha,
        "parameter_count": 57_579_201,
        "real_data": False,
        "data_kind": data_kind,
        "data_classes": [data_kind],
        "data_verified_for_promotion": data_verified,
        "modalities_tested": list(REQUIRED_METRICS),
        "split_manifest_sha256": test_hash,
    }
    return {
        **values,
        "split": "validation",
        "checkpoint_sha256": checkpoint_sha,
        "parameter_count": 57_579_201,
        "real_data": False,
        "data_kind": data_kind,
        "data_classes": [data_kind],
        "data_verified_for_promotion": data_verified,
        "modalities_tested": list(REQUIRED_METRICS),
        "quality_thresholds": thresholds,
        "split_manifest_sha256": validation_hash,
        "test_manifest_sha256": test_hash,
        "test_metrics": test_metrics,
    }


def test_verified_synthetic_corpus_can_pass_gate_when_all_evidence_and_thresholds_pass():
    passed, failures = promotion_gate(_metrics(data_verified=True))
    assert passed
    assert failures == []


def test_bootstrap_or_unverified_synthetic_corpus_is_blocked():
    passed, failures = promotion_gate(_metrics(data_verified=False, data_kind="synthetic_bootstrap"))
    assert not passed
    assert any("validation corpus is bootstrap or unverified" in failure for failure in failures)
    assert any("test corpus is bootstrap or unverified" in failure for failure in failures)


def test_verified_synthetic_manifest_requires_reference_verification_evidence(tmp_path):
    record = {
        "id": "math-verified-0001",
        "task": "text",
        "license": "local-owner-synthetic",
        "source_url": "local://onecore-cognitive-math",
        "attribution": "Generated by the OneCore verified curriculum",
        "split": "train",
        "review_status": "verified",
        "data_class": "synthetic_verified",
        "verification": {"method": "exact integer arithmetic", "reference": "7 * 8 = 56"},
        "text": "Compute 7 times 8. The verified answer is 56.",
    }
    report = validate_manifest([record], tmp_path, expected_split="train")
    assert report["valid"]
    assert classify_record_data(record) == "synthetic_verified"
