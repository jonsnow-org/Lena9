/**
 * تطبيع نص عربي (وأي نص عموماً) لأغراض البحث فقط — لا يُستخدم للعرض أبداً.
 *
 * البحث بالمطابقة الحرفية الصارمة (`.includes()` خام) كان يفشل بصمت لأي
 * فرق شكلي بسيط بين نص البحث والحقل الفعلي شائع جداً في الكتابة العربية:
 * أشكال الألف (أ/إ/آ/ا)، الياء المقصورة مقابل الياء (ى/ي)، التاء
 * المربوطة مقابل الهاء (ة/ه)، التشكيل، ومسافات متعددة/زائدة — فيبدو
 * البحث للمستخدم وكأنه "لا يعمل" رغم وجود الحساب/المقال فعلاً.
 */
export function normalizeArabicSearch(text: string): string {
  return text
    .toLowerCase()
    .normalize('NFKC')
    // إزالة التشكيل (الحركات) — نطاق يونيكود الحركات العربية القياسي
    .replace(/[ً-ٰٟ]/g, '')
    // توحيد أشكال الألف (أ/إ/آ) إلى ا
    .replace(/[أإآ]/g, 'ا')
    // الياء المقصورة (ى) ← ياء (ي)
    .replace(/ى/g, 'ي')
    // التاء المربوطة (ة) ← هاء (ه)
    .replace(/ة/g, 'ه')
    // مسافات متعددة ← مسافة واحدة، وقص الأطراف
    .replace(/\s+/g, ' ')
    .trim();
}
