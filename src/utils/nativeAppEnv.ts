/**
 * كشف "هل الموقع يعمل الآن داخل غلاف تطبيق أصلي (APK مبني بـ Capacitor)
 * أو داخل متصفح ويب عادي؟" — يُستخدم حصراً لبوابة الإعلانات (انظر
 * externalAdsStore.ts): شبكة إعلانية غير مؤكَّدة التوافق مع سياسات
 * التطبيقات (AdSense تحديداً، وأي شبكة أخرى لم يُتحقق من سياستها بعد)
 * يجب ألا تظهر أبداً داخل التطبيق حتى لو كانت مفعّلة للموقع، تفادياً
 * لمخالفة سياسات تلك الشبكات ومخاطرة تعليق الحساب.
 *
 * `window.Capacitor` علامة قياسية يضيفها Capacitor نفسه تلقائياً لأي صفحة
 * تعمل داخل تطبيقه — غير موجودة إطلاقاً في متصفح ويب عادي، فهذا الفحص
 * آمن 100% ولا يغيّر أي سلوك حالي للموقع (لا يوجد تطبيق Capacitor مبني
 * بعد، فهذه الدالة تُرجع false دائماً حتى إشعار آخر).
 */
export function isRunningInNativeApp(): boolean {
  return typeof window !== 'undefined' && Boolean((window as any).Capacitor);
}
