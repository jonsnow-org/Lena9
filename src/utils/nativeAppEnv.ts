import { isRunningAsInstalledApp } from './installState';

/**
 * كشف "هل الموقع يعمل الآن داخل التطبيق المثبَّت (APK) أو داخل متصفح ويب
 * عادٍ؟" — يُستخدم حصراً لبوابة الإعلانات (انظر externalAdsStore.ts):
 * شبكة إعلانية غير مؤكَّدة التوافق مع سياسات التطبيقات (AdSense تحديداً،
 * وأي شبكة أخرى لم يُتحقق من سياستها بعد) يجب ألا تظهر أبداً داخل
 * التطبيق حتى لو كانت مفعّلة للموقع، تفادياً لمخالفة سياسات تلك الشبكات
 * ومخاطرة تعليق الحساب.
 *
 * ⚠️ كانت هذه الدالة تفحص `window.Capacitor` — علامة خاصة بأطر عمل
 * Capacitor فقط. تطبيق هذا المشروع الفعلي مبني كـ TWA عبر Bubblewrap
 * (يفتح الموقع الحي داخل غلاف Chrome)، وهذا الإطار لا يضع علامة
 * Capacitor إطلاقاً — فكانت الدالة تُرجع false دائماً حتى داخل التطبيق
 * المثبَّت فعلياً، ما يعني تعطّل بوابة الحماية بالكامل: أي شبكة
 * appSafe:false (الافتراضي لأي شبكة) كانت ستظهر داخل التطبيق أيضاً رغم
 * أن الغرض الصريح من هذا الكود منعها هناك تحديداً. الآن تُستخدم نفس
 * دالة الكشف الصحيحة المبنية فعلاً لهذا التطبيق (installState.ts).
 */
export function isRunningInNativeApp(): boolean {
  return isRunningAsInstalledApp();
}
